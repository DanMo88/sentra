#!/usr/bin/env python3
"""Build js/data.js + tools/tts_jobs.json.
Lesson 1 = content/a1-01.txt (EN | FA | hand reading). Lessons 2..142 = Sentix course base (tools/sentix_base.json)
+ content/extra/<lv>.txt ("## <n>" then EN | FA), deduped, 25 sentences each.
Readings: content/pron.txt overrides, else CMUdict via tools/fa_pron.py (Sentix rules).
Usage: python3 tools/build.py [--max-level B1]"""
import json, os, re, sys, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fa_pron
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["A1", "A2", "B1", "B2", "C1", "C2"]
PER = 25
ZW = "\u200c"
def slug(t): return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")[:80].strip("-")
def bare(w): return re.sub(r"[^A-Za-z'\-]", "", w).strip("-'") or re.sub(r"[^A-Za-z]", "", w)
def key(en):
    t = en.lower().replace("’", "'")
    for a, b in (("n't", " not"), ("'m", " am"), ("'re", " are"), ("'ll", " will"), ("'s", " is"), ("'ve", " have"), ("'d", " would")):
        t = t.replace(a, b)
    return re.sub(r"[^a-z]", "", t)
def fa_fix(t):
    t = t.replace("~", ZW)
    t = re.sub(r"(^|[\s«(])(ن?می) (?=[\u0600-\u06FF])", lambda m: m.group(1) + m.group(2) + ZW, t)
    t = re.sub(r"(?<=[\u0600-\u06FF]) (ها|های|هایی|تر|ترین)(?=[\s.،؛:!؟»)]|$)", ZW + r"\1", t)
    t = t.replace("?", "؟").replace(",", "،").replace(";", "؛")
    return re.sub(r"\s+", " ", t).strip()
PRON = {}
for ln in open(os.path.join(ROOT, "content", "pron.txt"), encoding="utf-8"):
    ln = ln.strip()
    if ln and not ln.startswith("#") and " = " in ln:
        k, v = ln.split(" = ", 1); PRON[k.strip().lower()] = v.strip()
PUN = {",": "،", "?": "؟", ";": "؛", ".": ".", "!": "!", ":": ":"}
errors, unknown = [], {}
def reading(en):
    out = []
    for tok in en.split():
        core = re.sub(r"^[^A-Za-z0-9]+|[^A-Za-z0-9]+$", "", tok)
        tail = tok[len(tok.rstrip(".,!?;:\"”)")):]
        c = core.lower()
        r = PRON.get(c) or fa_pron.word(c)
        if not r:
            unknown.setdefault(c, en); r = "?"
        if " " in r: errors.append(f"space in reading {c}")
        out.append(r + "".join(PUN.get(ch, "") for ch in tail))
    return " ".join(out)
def main():
    cap = ORDER.index(sys.argv[sys.argv.index("--max-level") + 1]) if "--max-level" in sys.argv else 5
    base = {l["n"]: l for l in json.load(open(os.path.join(ROOT, "tools", "sentix_base.json"), encoding="utf-8"))}
    extra = {}
    for f in glob.glob(os.path.join(ROOT, "content", "extra", "*.txt")):
        cur = None
        for ln in open(f, encoding="utf-8"):
            ln = ln.strip()
            if ln.startswith("## "): cur = int(ln[3:]); extra.setdefault(cur, []); continue
            if not ln or ln.startswith("#"): continue
            en, fa = [x.strip() for x in ln.split("|")]
            extra[cur].append([en, fa])
    lessons, jobs, n = [], {}, 0
    lvnum = {}
    gseen = set()
    for gn in range(1, 143):
        b = base[gn]; lv = b["level"]
        if ORDER.index(lv) > cap: break
        lvnum[lv] = lvnum.get(lv, 0) + 1
        if gn == 1:
            lines = [l for l in open(os.path.join(ROOT, "content", "a1-01.txt"), encoding="utf-8").read().splitlines() if l.strip() and not l.startswith("#")]
            rows = [[x.strip() for x in l.split("|")] for l in lines]; title = "سلام و آشنایی"
        else:
            seen, rows = set(), []
            for en, fa in b["s"] + extra.get(gn, []):
                en = en.replace("’", "'").replace("“", '"').replace("”", '"')
                if key(en) in seen or key(en) in gseen: continue
                seen.add(key(en)); rows.append([en, fa, None])
            title = b["fa"]
            if len(rows) < PER: errors.append(f"lesson {gn} ({lv}) needs {PER - len(rows)} more: " + " / ".join(r[0] for r in rows))
            rows = rows[:PER]
        gseen.update(key(r[0]) for r in rows)
        out = []
        n0 = n + 1
        for en, fa, *rd in rows:
            n += 1
            rd = rd[0] if rd and rd[0] else reading(en)
            ws, rs = en.split(), rd.split()
            if len(ws) != len(rs): errors.append(f"token mismatch {en} / {rd}")
            for w in ws:
                bw = bare(w)
                if not bw: errors.append(f"empty word in {en!r}"); continue
                jobs.setdefault(f"audio/w-{slug(bw)}.mp3", {"text": bw, "voice": "w"})
            jobs[f"audio/s{n:04d}.mp3"] = {"text": en, "voice": "f" if n % 2 else "m"}
            out.append([en, fa_fix(fa), rd])
        lessons.append({"id": f"{lv.lower()}-{lvnum[lv]:02d}", "level": lv, "num": lvnum[lv], "title": title, "n0": n0, "s": out})
    if unknown:
        print("UNKNOWN WORDS:"); [print(f"{k} = ?   # {v}") for k, v in sorted(unknown.items())]
    if errors: print("ERRORS:", *errors, sep="\n")
    if unknown or errors: sys.exit(1)
    open(os.path.join(ROOT, "js", "data.js"), "w", encoding="utf-8").write(
        "/* generated by tools/build.py */\nwindow.SENTRA_LESSONS = " + json.dumps(lessons, ensure_ascii=False, separators=(",", ":")) + ";\n")
    json.dump(jobs, open(os.path.join(ROOT, "tools", "tts_jobs.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    from collections import Counter
    c = Counter(l["level"] for l in lessons); s = Counter()
    for l in lessons: s[l["level"]] += len(l["s"])
    print(dict(c), dict(s), "sentences", n, "audio jobs", len(jobs))
main()
