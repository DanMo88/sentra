#!/usr/bin/env python3
"""content/*.txt -> js/data.js + tools/tts_jobs.json. Sentences alternate voices (odd = female Aria, even = male Andrew)."""
import json, os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def slug(t):
    return re.sub(r"[^a-z0-9]+", "-", t.lower().replace("’", "'")).strip("-")[:80].strip("-")
def words(en):
    return [w for w in en.split() if w]
def bare(w):
    return re.sub(r"[^A-Za-z'\-]", "", w)
lessons, jobs, gnum = [], {}, 0
for f in sorted(glob.glob(os.path.join(ROOT, "content", "[a-c][1-2]-*.txt"))):
    lines = open(f, encoding="utf-8").read().splitlines()
    head = lines[0].lstrip("# ").split("·")
    lv = os.path.basename(f)[:2].upper(); num = int(os.path.basename(f)[3:5])
    sents = []
    for ln in lines:
        if not ln.strip() or ln.startswith("#"): continue
        en, fa, rd = [x.strip() for x in ln.split("|")]
        ws, rs = words(en), rd.split()
        assert len(ws) == len(rs), (en, rd)
        gnum += 1
        voice = "f" if gnum % 2 else "m"
        sid = f"s{gnum:04d}"
        jobs[f"audio/{sid}.mp3"] = {"text": en, "voice": voice}
        toks = []
        for w, r in zip(ws, rs):
            b = bare(w)
            wf = f"audio/w-{slug(b)}.mp3"
            jobs.setdefault(wf, {"text": b, "voice": "w"})
            toks.append({"w": w, "r": r, "a": f"w-{slug(b)}"})
        sents.append({"id": sid, "n": gnum, "en": en, "fa": fa, "rd": rd, "v": voice, "t": toks})
    lessons.append({"id": f"{lv.lower()}-{num:02d}", "level": lv, "num": num, "title": head[2].strip(), "fa": head[3].strip(), "s": sents})
open(os.path.join(ROOT, "js", "data.js"), "w", encoding="utf-8").write(
    "/* generated by tools/build.py */\nwindow.SENTRA_LESSONS = " + json.dumps(lessons, ensure_ascii=False, separators=(",", ":")) + ";\n")
json.dump(jobs, open(os.path.join(ROOT, "tools", "tts_jobs.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print(len(lessons), "lessons", gnum, "sentences", len(jobs), "audio jobs")
